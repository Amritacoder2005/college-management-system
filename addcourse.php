        <h1 id="a">HISTORY</h1>
    <P id="b">Balrampur, the erstwhile princely state of pre independent era, was actively involved in removing educational backwardness of the terai region by establishing schools and colleges. Immediately after getting independence, a great philanthropist Late Maharaja Pateshwari Prasad Singh took a giant step by establishing M. L. K. College in 1955 in the loving memory of his mother Maharani Lal Kunwari.With the passage of time this college became cradle for learning and research for the students belonging to terai region. This was the reason that the then governor his highness Sri K.M. Munshi in his inaugural speech on August 1955 said, this college is one of the rarest colleges to which I have offered affiliation with delight. This college is furnished with a good building, good economic sources and accomplishments. It has some rare qualities which are not found in other colleges of Uttar Pradesh.” (Adapted from the letter of the V.C., Bhartiya Vidya Bhawan).
         <br>
         <br>
        <img src="pic.jpg" alt="" class="d-block w-100">
        <br>
        The college was initially affiliated to Agra University, Agra. Later on it got affiliated to DDU Gorakhpur University, Gorakhpur and Dr. R M L Awadh University, Ayodhya. Presently it is one of the premier colleges affiliated to Sidharth University Kapilvastu, Sidharth Nagar.The college was assessed & accredited by NAAC in 2011. The Peer team observed minutely the academic standards of the college, consisting of teaching, research and co-curricular activities beneficial to the students and awarded 3.25 CGPA out of 4 and thus decorating the college with grade ‘A’. This was the only college among all the aided colleges of Dr. R.M.L. Awadh University, Ayodhya that has got the honor of having grade ‘A’ at that time.
        <br>
        <br>
        In 1969, the then Chief Minister U.P. Honorable Chandra Bhan Gupta, being impressed by its fine-infrastructure said, “Had I seen this college earlier, I would have got Gorakhpur University built here”.
        <br>
        <br>
        In April 1994 while addressing the convocation the then H.R.D. Minister Honorable Arjun Singh, praising the college said, “I was already aware of the fame of this college. Today I came here and was very much delighted. I heartily wish that this college should be doing great in academic spheres in U.P.”
        <br>
        <br>
        This college has been progressing continuously. The academic journey of the college has been- B.Ed. course 1960; P.G. courses in Botany & Chemistry, 1970 and Physics, Maths.,Geography, Political Science, Hindi & Sanskrit, 1971; P.G.D.C.A. course, 1986; Seed Technology as a subject in 1990.
        <br>
        <br>
        Since 2004-05 the P.G. courses for Zoology & Psychology & B. Com courses were started for the convenience of the local students. For raising the education standard of the students learned lectures and national seminars have been organized with the financial help of UGC New Delhi. Three National Seminars were held during the period of 2010-2013 in which eminent personalities from different part of the country and delegates from Nepal also participated.
        <br>
        <br>
        Recognizing the importance of occupational education, the college started B.C.A. & B.B.A. since 2010-2011 session. Home Science has been started in Arts faculty since 2013-2014 session.
        <br>
        <br>
        The college is fortunate enough to get Rs 30 lacs as financial aid from U.G.C. New Delhi under 10th Five Year Plan and Rs 21 lacs for UG development and 31 lacs for P.G. development during the 11th Five Year Plan.
        <br>
        <br>
        The college campus is furnished with Wi-Fi facility and the whole campus is covered with CCTV. The college maintains a well-furnished library. Seven hundred research scholars have been awarded Ph.D. degree till now. There are seven subjects in B.Sc. and 13 subjects in B.A. . It has the privilege of running P.G. courses for Chemistry, Botany, Physics, Mathematics, Geography, Political Science, Sanskrit, Hindi under grant in aid scheme; Zoology, Psychology, Education, English & M. Com. Under self-finance scheme.
        <br>
        <br>
        Music course has been added in the list of UG subjects and Sociology as PG subject since 2018-2019 under SFS. The college is constantly engaged in organizing learned lectures and granting opportunities to the students to participate in cultural and athletic events. The college ever had the potentialities of growth and it still has that potentiality and also has the courage to cope with the times to come.
        <br>
        <br>
        Thus, being associated with Siddhartha University, Kapilvastu, Siddharth Nagar, it is contributing to qualitative education under the guidance of proactive & visionary committee of management, principal and learned and experienced faculty members. Not only the college family but also the people of terai region feel proud of this institution.</P>
